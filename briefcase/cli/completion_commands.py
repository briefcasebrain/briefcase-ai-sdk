"""``briefcase-ai completion bash|zsh|fish``: print a shell completion script.

    eval "$(briefcase-ai completion bash)"            # this shell only
    briefcase-ai completion zsh > ~/.zfunc/_briefcase_ai # then: fpath+=(~/.zfunc); compinit
    briefcase-ai completion fish > ~/.config/fish/completions/briefcase-ai.fish

The script is generated from the argparse tree at the moment the command runs, so it covers
every discovered command, subcommand, flag and fixed choice. It is static: re-generate it
after upgrading. Nothing is written by this command; it only prints.
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass, field
from typing import List, Optional, Tuple

from briefcase.cli import _ux

GROUP = "start"
ORDER = 90
SHELLS = ("bash", "zsh", "fish")
PROG = "briefcase-ai"


def register(sub) -> None:
    p = sub.add_parser(
        "completion",
        help="Print a shell completion script (bash, zsh or fish).",
        description="Print a completion script for your shell, generated from the commands "
                    "installed right now. Nothing is written; redirect or eval the output.",
        epilog='example:\n  eval "$(briefcase-ai completion bash)"',
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("shell", choices=SHELLS, help="Which shell to generate for.")
    p.set_defaults(func=cmd_completion)


# --- the argparse tree as plain data --------------------------------------------

@dataclass
class Option:
    flags: List[str]
    help: str = ""
    takes_value: bool = False
    choices: List[str] = field(default_factory=list)


@dataclass
class Node:
    path: Tuple[str, ...]                                     # ("briefcase-ai", "run", "submit")
    options: List[Option] = field(default_factory=list)
    subcommands: List[Tuple[str, str]] = field(default_factory=list)   # (name, help)
    positional_choices: List[str] = field(default_factory=list)

    @property
    def key(self) -> str:
        return " ".join(self.path)


def _clean(text: Optional[str], limit: int = 70) -> str:
    """Help text reduced to one short line of characters that are safe inside single quotes
    in every supported shell."""
    if not text or text == argparse.SUPPRESS:
        return ""
    text = re.sub(r"[^A-Za-z0-9 .,/()=+_-]", "", " ".join(text.split()))
    return text if len(text) <= limit else text[: limit - 3].rstrip() + "..."


def _word(text: str) -> bool:
    return bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", text))


def tree(parser: argparse.ArgumentParser, path: Tuple[str, ...] = (PROG,)) -> List[Node]:
    """Flatten ``parser`` into one ``Node`` per command path, root first."""
    node = Node(path=path)
    nodes = [node]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {choice.dest: choice.help for choice in action._choices_actions}
            for name, child in action.choices.items():
                if not _word(name):
                    continue
                node.subcommands.append((name, _clean(helps.get(name))))
                nodes.extend(tree(child, path + (name,)))
            continue
        if action.help == argparse.SUPPRESS:
            continue
        choices = [str(c) for c in (action.choices or []) if _word(str(c))]
        if not action.option_strings:
            node.positional_choices.extend(choices)
            continue
        node.options.append(Option(
            flags=[flag for flag in action.option_strings if re.fullmatch(r"--?[A-Za-z0-9][A-Za-z0-9-]*", flag)],
            help=_clean(action.help), takes_value=action.nargs != 0, choices=choices,
        ))
    return nodes


# --- bash -----------------------------------------------------------------------

def bash_script(nodes: List[Node]) -> str:
    descend = [f'"{node.key}"' for node in nodes[1:]]
    values, free, words = [], [], []
    for node in nodes:
        for option in node.options:
            keys = "|".join(f'"{node.key} {flag}"' for flag in option.flags)
            if option.choices:
                values.append(f'        {keys}) words="{" ".join(option.choices)}" ;;')
            elif option.takes_value and keys:
                free.append(keys)
        candidates = [name for name, _ in node.subcommands] + node.positional_choices
        candidates += [flag for option in node.options for flag in option.flags]
        words.append(f'        "{node.key}") words="{" ".join(candidates)}" ;;')
    lines = [
        "# bash completion for briefcase-ai. Generated by `briefcase-ai completion bash`.",
        '# Load it in this shell with:  eval "$(briefcase-ai completion bash)"',
        "_briefcase_ai() {",
        "    local cur prev ctx word i words",
        "    COMPREPLY=()",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev=""',
        '    if (( COMP_CWORD > 0 )); then prev="${COMP_WORDS[COMP_CWORD-1]}"; fi',
        '    ctx="briefcase-ai"',
        "    for (( i = 1; i < COMP_CWORD; i++ )); do",
        '        word="${COMP_WORDS[i]}"',
        "        # after a literal -- the rest belongs to another program (briefcase-ai exec -- ...)",
        '        if [[ "$word" == "--" ]]; then return 0; fi',
        '        case "$ctx $word" in',
        "            " + "|".join(descend) + ') ctx="$ctx $word" ;;' if descend else "            *) ;;",
        "        esac",
        "    done",
        '    words=""',
        '    case "$ctx $prev" in',
        *values,
        *([f"        {'|'.join(free)}) return 0 ;;"] if free else []),
        "        *) ;;",
        "    esac",
        '    if [[ -z "$words" ]]; then',
        '    case "$ctx" in',
        *words,
        "        *) ;;",
        "    esac",
        "    fi",
        '    COMPREPLY=( $(compgen -W "$words" -- "$cur") )',
        "    return 0",
        "}",
        "complete -o default -F _briefcase_ai briefcase-ai",
    ]
    return "\n".join(lines) + "\n"


# --- zsh ------------------------------------------------------------------------

def zsh_script(nodes: List[Node]) -> str:
    descend = [f'"{node.key}"' for node in nodes[1:]]
    values, free, contexts = [], [], []
    for node in nodes:
        for option in node.options:
            keys = "|".join(f'"{node.key} {flag}"' for flag in option.flags)
            if option.choices:
                values.append(f"    {keys}) vals=({' '.join(option.choices)}) ;;")
            elif option.takes_value and keys:
                free.append(keys)
        commands = " ".join(f"'{name}:{help_}'" if help_ else f"'{name}'" for name, help_ in node.subcommands)
        flags = " ".join([flag for option in node.options for flag in option.flags] + node.positional_choices)
        contexts.append(f'    "{node.key}") cmds=({commands}); opts=({flags}) ;;')
    lines = [
        "#compdef briefcase-ai",
        "# zsh completion for briefcase-ai. Generated by `briefcase-ai completion zsh`.",
        "# Load it in this shell with:  source <(briefcase-ai completion zsh)",
        "_briefcase_ai() {",
        "  local ctx word prev i",
        "  local -a cmds opts vals",
        '  ctx="briefcase-ai"',
        '  prev="${words[CURRENT-1]}"',
        "  for (( i = 2; i < CURRENT; i++ )); do",
        '    word="${words[i]}"',
        '    if [[ "$word" == "--" ]]; then _default; return; fi',
        '    case "$ctx $word" in',
        "      " + "|".join(descend) + ') ctx="$ctx $word" ;;' if descend else "      *) ;;",
        "    esac",
        "  done",
        '  case "$ctx $prev" in',
        *values,
        *([f"    {'|'.join(free)}) _default; return ;;"] if free else []),
        "    *) ;;",
        "  esac",
        "  if (( ${#vals} )); then compadd -a vals; return; fi",
        '  case "$ctx" in',
        *contexts,
        "    *) ;;",
        "  esac",
        "  if (( ${#cmds} )); then _describe -t commands 'briefcase command' cmds; fi",
        "  if (( ${#opts} )); then compadd -a opts; fi",
        "  if (( ! ${#cmds} && ! ${#opts} )); then _default; fi",
        "}",
        'if [[ "${funcstack[1]}" == "_briefcase_ai" ]]; then',
        '  _briefcase_ai "$@"',
        "else",
        "  compdef _briefcase_ai briefcase-ai",
        "fi",
    ]
    return "\n".join(lines) + "\n"


# --- fish -----------------------------------------------------------------------

def fish_script(nodes: List[Node]) -> str:
    descend = " ".join(f'"{node.key}"' for node in nodes[1:])
    lines = [
        "# fish completion for briefcase-ai. Generated by `briefcase-ai completion fish`.",
        "# Install: briefcase-ai completion fish > ~/.config/fish/completions/briefcase-ai.fish",
        "function __briefcase_ai_ctx",
        "    set -l tokens (commandline -opc)",
        "    set -l ctx briefcase-ai",
        "    set -e tokens[1]",
        "    for token in $tokens",
        "        if test \"$token\" = \"--\"",
        "            echo stop",
        "            return",
        "        end",
        "        switch \"$ctx $token\"",
        f"            case {descend}" if descend else "            case __none__",
        "                set ctx \"$ctx $token\"",
        "        end",
        "    end",
        "    echo $ctx",
        "end",
        "function __briefcase_ai_at",
        "    test (__briefcase_ai_ctx) = \"$argv[1]\"",
        "end",
        "complete -c briefcase-ai -e",
    ]
    for node in nodes:
        condition = f"-n '__briefcase_ai_at \"{node.key}\"'"
        files = "" if node.key != PROG else " -f"
        for name, help_ in node.subcommands:
            lines.append(f"complete -c briefcase-ai{files} {condition} -a {name}" + (f" -d '{help_}'" if help_ else ""))
        for choice in node.positional_choices:
            lines.append(f"complete -c briefcase-ai -f {condition} -a {choice}")
        for option in node.options:
            spec = "".join(f" -l {flag[2:]}" if flag.startswith("--") else f" -s {flag[1:]}"
                           for flag in option.flags if flag.startswith("--") or len(flag) == 2)
            if not spec:
                continue
            if option.choices:
                spec += f" -x -a '{' '.join(option.choices)}'"
            elif option.takes_value:
                spec += " -r"
            lines.append(f"complete -c briefcase-ai {condition}{spec}" + (f" -d '{option.help}'" if option.help else ""))  # noqa: E501
    return "\n".join(lines) + "\n"


GENERATORS = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}


def script(shell: str, parser: Optional[argparse.ArgumentParser] = None) -> str:
    """The completion script for ``shell``, generated from ``parser`` (default: the full CLI)."""
    if parser is None:
        from briefcase.cli.__main__ import build_parser

        parser = build_parser()
    return GENERATORS[shell](tree(parser))


def cmd_completion(args, store=None, engine=None, stack=None) -> int:
    shell = getattr(args, "shell", None)
    if shell not in GENERATORS:
        return _ux.fail(f"unsupported shell {shell!r}", fix="briefcase-ai completion bash", code=_ux.EXIT_USAGE)
    print(script(shell), end="")
    return 0
