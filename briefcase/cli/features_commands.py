"""``briefcase-ai features``: the feature catalog, generated from ``briefcase/_features/*.json``.

    briefcase-ai features                  # everything, grouped by verb
    briefcase-ai features --verb enforce   # one group
    briefcase-ai features connect          # one feature: docs link, and whether it is on here
    briefcase-ai features --json

A feature appears here when its manifest exists; see ``briefcase/features.py`` for the schema.
"""
from __future__ import annotations

import argparse
import difflib
from typing import Any, Callable, Dict, Optional

from briefcase.cli import _ux
from briefcase.features import VERB_TITLES, VERBS, Catalog, Feature, load_catalog

GROUP = "start"
ORDER = 30


def register(sub) -> None:
    p = sub.add_parser(
        "features",
        help="Browse everything briefcase can do, grouped by Connect, Capture, Enforce, Verify, Review.",
        description="The feature catalog. Each entry has a title, what it gives you, the first "
                    "command to run and whether it is stable or experimental. Name one feature to "
                    "see its documentation link and whether it is active on this machine.",
        epilog="example:\n  briefcase-ai features --verb connect",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("feature", nargs="?", metavar="ID", help="Show one feature (ids are listed in the catalog).")
    p.add_argument("--verb", choices=VERBS, help="Only this group.")
    _ux.add_json_flag(p)
    p.add_argument("--markdown", action="store_true",
                   help="Print the catalog as the Markdown page kept in docs/features/catalog.md.")
    p.set_defaults(func=cmd_features)


def _warn(catalog: Catalog) -> None:
    import sys

    for problem in catalog.problems:
        print(f"warning: {problem}", file=sys.stderr)


def _plural(count: int, word: str) -> str:
    return f"{count} {word}" + ("" if count == 1 else "s")


def render_catalog(catalog: Catalog, verb: Optional[str] = None, out: Callable[[str], Any] = print) -> None:
    groups = [(key, items) for key, items in catalog.groups() if verb in (None, key)]
    total = sum(len(items) for _, items in groups)
    out(_ux.style("briefcase-ai features", "bold") + f" · {_plural(total, 'feature')} · {_plural(len(groups), 'group')}")  # noqa: E501
    for key, items in groups:
        out("")
        out(_ux.style(f"{VERB_TITLES[key]} ({len(items)})", "bold"))
        for feature in items:
            badge = _ux.style(f"[{feature.status}]", "green" if feature.status == "stable" else "yellow")
            plugin = feature.extra.get("plugin")
            origin = _ux.style(f"  plugin: {plugin}", "dim") if plugin else ""
            out(f"  {feature.title}  {badge}  " + _ux.style(f"id: {feature.id}", "dim") + origin)
            out(f"      {feature.one_line}")
            out(f"      $ {feature.command}")
    if not groups:
        out("")
        out("No features are listed in this install.")
    out("")
    _ux.print_next("briefcase-ai features <id>", "details, docs link and whether it is on here", out=out)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_markdown(catalog: Catalog) -> str:
    """The docs catalog (``docs/features/catalog.md``), from the same manifests as the
    terminal listing. Links are relative to ``docs/features/``."""
    groups = catalog.groups()
    lines = [
        "<!-- Generated by `briefcase-ai features --markdown`. Do not edit: change the manifest in",
        "     briefcase/_features/ and regenerate with",
        "     `briefcase-ai features --markdown > docs/features/catalog.md`. -->",
        "# Feature catalog",
        "",
        f"{_plural(len(catalog.features), 'feature')} · {_plural(len(groups), 'group')}. The same list, with",
        "whether each feature is on for you, is in your terminal: `briefcase-ai features`.",
    ]
    for key, items in groups:
        lines += ["", f"## {VERB_TITLES[key]} ({len(items)})", "",
                  "| Feature | What it gives you | First command | Status |", "| --- | --- | --- | --- |"]
        for feature in items:
            lines.append(f"| [{_cell(feature.title)}](../../{feature.docs_file}) | {_cell(feature.one_line)} "
                         f"| `{_cell(feature.command)}` | {feature.status} |")
    return "\n".join(lines) + "\n"


def activity(feature: Feature, report: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Whether the feature is on here, from the ``briefcase-ai status`` row named by its
    ``status_id`` (default: its id). ``state`` is ``None`` when no row tracks it."""
    row_id = feature.status_id or feature.id
    for item in (report or {}).get("items", []):
        if item["id"] == row_id:
            return {"state": item["state"], "detail": item["detail"], "status_id": row_id}
    return {"state": None, "detail": "not tracked by `briefcase-ai status` (it is on when your code uses it)",
            "status_id": None}


def render_feature(feature: Feature, active: Dict[str, Any], out: Callable[[str], Any] = print) -> None:
    badge = _ux.style(f"[{feature.status}]", "green" if feature.status == "stable" else "yellow")
    out(_ux.style(feature.title, "bold") + f"  {badge}  {VERB_TITLES[feature.verb]}")
    out(feature.one_line)
    out("")
    own_page = f"briefcase-ai features {feature.id}"
    if feature.command != own_page:
        out(f"  Start with:    {feature.command}")
    if feature.requires_extra:
        out(f"  Needs:         pip install 'briefcase-ai[{feature.requires_extra}]'")
    state = active["state"]
    label = {"on": "yes", "off": "no", "attention": "yes, needs attention"}.get(state)
    out(f"  Active here:   {label} ({active['detail']})" if label else f"  Active here:   {active['detail']}")
    out(f"  Docs:          {feature.docs_file}")
    out(f"                 {feature.docs_url}")
    if feature.verified_against:
        out(f"  Verified with: {feature.verified_against}")
    if feature.snippet:
        out("")
        out("  In Python:")
        for line in feature.snippet.splitlines():
            out(f"      {line}" if line else "")
    out("")
    if feature.command != own_page and state != "on":
        _ux.print_next(feature.command, out=out)
    else:
        _ux.print_next("briefcase-ai status", "see what is on across this machine", out=out)


def cmd_features(args, store=None, engine=None, stack=None) -> int:
    # Plugin manifests are listed in the terminal; the docs page lists only what ships here.
    catalog = load_catalog(plugins=not getattr(args, "markdown", False))
    as_json = getattr(args, "json", False)
    verb = getattr(args, "verb", None)
    feature_id = getattr(args, "feature", None)
    _warn(catalog)

    if feature_id:
        feature = catalog.get(feature_id)
        if feature is None:
            close = difflib.get_close_matches(feature_id, [f.id for f in catalog.features], n=1)
            return _ux.fail(f"no feature with id {feature_id!r}",
                            fix=f"briefcase-ai features {close[0]}" if close else "briefcase-ai features",
                            code=_ux.EXIT_USAGE)
        from briefcase.cli import status_commands

        active = activity(feature, status_commands.collect())
        if as_json:
            return _ux.print_json(dict(feature.to_dict(), active=active))
        render_feature(feature, active)
        return 0

    if getattr(args, "markdown", False):
        print(render_markdown(catalog), end="")
        return 0
    if as_json:
        data = catalog.to_dict()
        if verb:
            data["groups"] = [group for group in data["groups"] if group["verb"] == verb]
            data["count"] = sum(group["count"] for group in data["groups"])
        data["group_count"] = len(data["groups"])
        return _ux.print_json(data)
    render_catalog(catalog, verb)
    return 0
