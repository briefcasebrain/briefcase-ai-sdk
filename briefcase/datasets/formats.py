"""Export a dataset version for other evaluation harnesses.

``jsonl``   the briefcase format: a header line, then one case per line.
            Hand-editable; ``briefcase-ai dataset import`` reads it back.
``inspect`` one inspect-ai ``Sample`` per line (``input``, ``target``, ``id``,
            ``metadata``), loadable with ``inspect_ai.dataset.json_dataset``.
            Field names checked against inspect-ai 0.3.291
            (``inspect_ai/dataset/_dataset.py`` ``Sample`` / ``FieldSpec``).
``lm-eval`` a docs JSONL (``id``, ``input``, ``target``) plus a task YAML
            (``dataset_path: json``, ``doc_to_text: "{{input}}"``, ...).
            Keys checked against lm-eval 0.4.13 (``lm_eval/config/task.py``
            ``TaskConfig`` and bundled task YAMLs). Experimental: the task has
            not been executed by lm-eval here.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List, Tuple

from briefcase.datasets.core import DatasetVersion, render_jsonl

EXPORT_FORMATS = ("jsonl", "inspect", "lm-eval")


def as_text(value: Any) -> str:
    """A case input or reference as one string for text-in/text-out harnesses.

    A single positional string argument is unwrapped; anything else becomes
    sorted-key JSON."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        args, kwargs = value.get("args"), value.get("kwargs")
        if set(value) <= {"args", "kwargs"}:
            if isinstance(args, list) and len(args) == 1 and not kwargs and isinstance(args[0], str):
                return args[0]
            if not args and isinstance(kwargs, dict) and len(kwargs) == 1:
                only = next(iter(kwargs.values()))
                if isinstance(only, str):
                    return only
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def export_jsonl(version: DatasetVersion) -> str:
    return render_jsonl(version.header, version.cases)


def inspect_samples(version: DatasetVersion) -> List[Dict[str, Any]]:
    samples = []
    for case in version.cases:
        metadata = dict(case.get("metadata") or {})
        metadata["briefcase_case_id"] = case["id"]
        metadata["briefcase_dataset"] = version.ref
        text = as_text(case["input"])
        if text != case["input"]:
            metadata["briefcase_input"] = case["input"]
        samples.append({
            "id": case["id"],
            "input": text,
            "target": as_text(case.get("reference")),
            "metadata": metadata,
        })
    return samples


def export_inspect(version: DatasetVersion) -> str:
    return "".join(json.dumps(s, ensure_ascii=False) + "\n" for s in inspect_samples(version))


def lm_eval_task_name(version: DatasetVersion) -> str:
    return "briefcase_" + re.sub(r"[^a-z0-9_]+", "_", f"{version.name}_{version.tag}".lower())


def lm_eval_docs(version: DatasetVersion) -> List[Dict[str, str]]:
    return [{"id": c["id"], "input": as_text(c["input"]), "target": as_text(c.get("reference"))}
            for c in version.cases]


def lm_eval_yaml(version: DatasetVersion, docs_path: Path) -> str:
    # JSON strings are valid YAML scalars, so quoting goes through json.dumps.
    q = json.dumps
    return "\n".join([
        f"# lm-eval task generated by briefcase from {version.ref} ({version.hash[:12]})",
        f"# Run: lm_eval --model <model> --model_args <args> --include_path {q(str(docs_path.parent))} "
        f"--tasks {lm_eval_task_name(version)}",
        f"task: {lm_eval_task_name(version)}",
        "dataset_path: json",
        "dataset_kwargs:",
        "  data_files:",
        f"    test: {q(str(docs_path))}",
        "test_split: test",
        "output_type: generate_until",
        f"doc_to_text: {q('{{input}}')}",
        f"doc_to_target: {q('{{target}}')}",
        "generation_kwargs:",
        "  until:",
        f"    - {q(chr(10) + chr(10))}",
        "  do_sample: false",
        "metric_list:",
        "  - metric: exact_match",
        "    aggregation: mean",
        "    higher_is_better: true",
        "metadata:",
        "  version: 1.0",
        "",
    ])


def export_lm_eval(version: DatasetVersion, docs_path: Path) -> Tuple[str, str]:
    """Return ``(docs_jsonl, task_yaml)`` for writing at ``docs_path`` and
    ``docs_path.with_suffix('.yaml')``."""
    docs = "".join(json.dumps(d, ensure_ascii=False) + "\n" for d in lm_eval_docs(version))
    return docs, lm_eval_yaml(version, docs_path.resolve())
